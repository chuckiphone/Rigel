//! Roadmap 142: the real CLI generates all four shells, installs each through its own path, and
//! treats an unknown flag or shell as an error rather than a silent no-op.

use std::path::Path;
use std::process::Command;

use serde_json::Value;
use tempfile::TempDir;

fn rigel(data: &Path, args: &[&str]) -> (i32, Vec<u8>, String) {
    let output = Command::new(env!("CARGO_BIN_EXE_rigel"))
        .arg("--data-dir")
        .arg(data)
        .args(args)
        .output()
        .expect("rigel runs");
    (
        output.status.code().unwrap_or(-1),
        output.stdout,
        String::from_utf8_lossy(&output.stderr).into_owned(),
    )
}

const SHELLS: [(&str, &str, &str); 4] = [
    ("bash", "rigel", "_rigel()"),
    ("zsh", "_rigel", "#compdef rigel"),
    ("fish", "rigel.fish", "complete -c rigel"),
    ("powershell", "rigel.ps1", "Register-ArgumentCompleter"),
];

#[test]
fn each_shell_gets_a_script_generated_from_the_live_command_tree() {
    let tmp = TempDir::new().unwrap();
    let data = tmp.path().join("data");
    std::fs::create_dir_all(&data).unwrap();

    for (shell, _, marker) in SHELLS {
        let (code, stdout, stderr) = rigel(&data, &["completions", "generate", "--shell", shell]);
        assert_eq!(code, 0, "{shell}: {stderr}");
        let text = String::from_utf8_lossy(&stdout);
        assert!(text.contains(marker), "{shell} script is missing {marker}");
        assert!(
            text.contains("completions"),
            "{shell} script is missing the new subcommand"
        );
        assert!(
            text.contains("hooks"),
            "{shell} script is generated from Cli"
        );
    }
}

#[test]
fn each_install_path_writes_the_exact_generated_bytes() {
    let tmp = TempDir::new().unwrap();
    let data = tmp.path().join("data");
    let dir = tmp.path().join("completions");
    std::fs::create_dir_all(&data).unwrap();
    let dir_arg = dir.to_string_lossy().into_owned();

    for (shell, file, _) in SHELLS {
        let (code, stdout, stderr) = rigel(&data, &["completions", "generate", "--shell", shell]);
        assert_eq!(code, 0, "{stderr}");

        let (code, stdout_json, stderr) = rigel(
            &data,
            &[
                "completions",
                "install",
                "--shell",
                shell,
                "--dir",
                &dir_arg,
                "--json",
            ],
        );
        assert_eq!(code, 0, "{shell}: {stderr}");
        let report: Value = serde_json::from_slice(&stdout_json).unwrap();
        assert_eq!(report["shell"], shell);
        assert_eq!(
            Path::new(report["path"].as_str().unwrap()),
            dir.join(file),
            "{shell} installs under its own file name"
        );
        assert_eq!(
            std::fs::read(dir.join(file)).unwrap(),
            stdout,
            "{shell} installed bytes equal generated bytes"
        );
        assert_eq!(report["bytes"].as_u64().unwrap() as usize, stdout.len());
    }
}

#[test]
fn the_path_command_names_the_default_install_location_without_writing() {
    let tmp = TempDir::new().unwrap();
    let data = tmp.path().join("data");
    std::fs::create_dir_all(&data).unwrap();

    let (code, stdout, stderr) = rigel(&data, &["completions", "path", "--shell", "zsh"]);
    assert_eq!(code, 0, "{stderr}");
    let path = String::from_utf8_lossy(&stdout).trim().to_string();
    assert!(path.ends_with("_rigel"), "{path}");
    assert!(
        !Path::new(&path).exists(),
        "path only prints; install writes"
    );
}

#[test]
fn an_unknown_flag_or_shell_is_an_error_not_silence() {
    let tmp = TempDir::new().unwrap();
    let data = tmp.path().join("data");
    std::fs::create_dir_all(&data).unwrap();

    let (code, _, stderr) = rigel(&data, &["--not-a-real-flag"]);
    assert_ne!(code, 0, "an unknown flag cannot pass");
    assert!(stderr.contains("--not-a-real-flag"), "{stderr}");

    let (code, _, stderr) = rigel(&data, &["completions", "generate", "--shell", "nope"]);
    assert_ne!(code, 0, "an unknown shell cannot pass");
    assert!(stderr.contains("invalid value"), "{stderr}");
}
