#!/usr/bin/env node
/**
 * Roadmap 124: the licence list the About dialog shows is derived from the same CycloneDX SBOM
 * the release publishes, never from a hand-written copy that can drift.
 *
 * Usage: node scripts/make-about-licences.mjs [--check]
 *   --check  verify the checked-in list still matches a freshly generated SBOM, write nothing.
 */

import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUTPUT = path.join(ROOT, "ui", "src", "about-licences.ts");

/** Generate a throwaway SBOM with the repository's own generator and read its licence set. */
export function aboutLicences(root = ROOT) {
  const scratch = mkdtempSync(path.join(tmpdir(), "rigel-about-"));
  try {
    const sbomPath = path.join(scratch, "sbom.cdx.json");
    execFileSync(
      process.execPath,
      [path.join(root, "scripts", "make-sbom.mjs"), sbomPath],
      { cwd: root, encoding: "utf8", stdio: "pipe" },
    );
    const bom = JSON.parse(readFileSync(sbomPath, "utf8"));
    const expressions = new Set();
    for (const component of bom.components ?? []) {
      for (const entry of component.licenses ?? []) {
        const name = entry?.license?.name;
        if (typeof name === "string" && name.trim()) expressions.add(name.trim());
      }
    }
    return {
      source: "CycloneDX 1.5 SBOM from scripts/make-sbom.mjs",
      components: (bom.components ?? []).length,
      expressions: [...expressions].sort(),
    };
  } finally {
    rmSync(scratch, { recursive: true, force: true });
  }
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const generated = aboutLicences();
  const body =
    "// Generated by scripts/make-about-licences.mjs from the release SBOM. Do not edit by hand.\n" +
    `export const ABOUT_LICENCES = ${JSON.stringify(generated, null, 2)} as const;\n`;
  if (process.argv.includes("--check")) {
    const checkedIn = readFileSync(OUTPUT, "utf8");
    if (checkedIn !== body) {
      console.error("about licences do not match the SBOM: run node scripts/make-about-licences.mjs");
      process.exitCode = 1;
    } else {
      console.log(
        `about licences: ${generated.components} SBOM components, ${generated.expressions.length} expressions — in sync`,
      );
    }
  } else {
    writeFileSync(OUTPUT, body, "utf8");
    console.log(`about licences: ${generated.components} components -> ${path.relative(ROOT, OUTPUT)}`);
  }
}
